"""Build index.html from index.src.html: shot clock, captions from the voice timings, audio clips."""
import html
import json
import re
from pathlib import Path

HERE = Path(__file__).parent
S = [0, 6.2, 12.4, 17.8, 23.2, 36.3, 42.1, 46.7, 52.5, 58.2]  # shot starts (s)
TOTAL = 62.5
VO = 0.35  # each line starts this long after its shot starts
DROPPED = [0, 1, 3, 4, 5, 7, 8, 10, 11, 13, 15, 17, 18, 20, 22, 23]  # 16 of 25 grid cells

voice = json.loads((HERE / "assets/voice/voice.json").read_text())
ends = S[1:] + [TOTAL]

# ---- captions: chunk each line at punctuation or 6 words
caps, cap_html = [], []
for i, line in enumerate(voice):
    if line["id"] == "v10":
        continue
    t0 = S[i] + VO
    chunks, cur = [], []
    for w in line["words"]:
        cur.append(w)
        if w["text"][-1] in ".,?:" or len(cur) >= 6:
            chunks.append(cur)
            cur = []
    if cur:
        chunks.append(cur)
    for k, ch in enumerate(chunks):
        cid = f"cap{i + 1:02d}_{k}"
        t_in = round(t0 + ch[0]["start"] - 0.12, 3)
        t_out = round(t0 + chunks[k + 1][0]["start"] - 0.12, 3) if k + 1 < len(chunks) else round(min(t0 + ch[-1]["end"] + 0.45, ends[i] - 0.05), 3)
        words = []
        spans = []
        for j, w in enumerate(ch):
            wid = f"{cid}w{j}"
            words.append([wid, round(t0 + w["start"], 3)])
            spans.append(f'<span id="{wid}">{html.escape(w["text"])}</span>')
        caps.append({"id": cid, "in": t_in, "out": t_out, "words": words})
        cap_html.append(f'          <div id="{cid}" class="cap">{" ".join(spans)}</div>')

# ---- audio
audio = []
def clip(id_, src, start, dur, vol, track, extra=""):
    audio.append(f'      <audio id="{id_}" class="clip" src="{src}" data-start="{start:.3f}" data-duration="{dur:.3f}" data-volume="{vol}" data-track-index="{track}"{extra}></audio>')

for i, line in enumerate(voice):
    clip(f"vo{i + 1:02d}", f"assets/voice/{line['id']}.mp3", S[i] + VO, line["duration"], 1, 2)
clip("music", "assets/music/bed.mp3", 0, 62.4, 0.16, 3, ' data-fade-out="2"')

SFX = [  # (file, shot, t, volume, duration)
    ("pop", 1, 0.3, 0.5, 0.7), ("pop", 1, 2.95, 0.4, 0.7), ("pop", 1, 3.95, 0.5, 0.7), ("pop", 1, 4.95, 0.6, 0.7),
    ("pop", 2, 1.85, 0.5, 0.7), ("pop", 2, 3.9, 0.7, 0.7),
    ("fall", 3, 0.3, 0.7, 1.0), ("pop", 3, 1.4, 0.4, 0.7), ("pop", 3, 3.1, 0.4, 0.7), ("stamp", 3, 3.82, 1.0, 0.8),
    ("whoosh", 4, 0.0, 0.6, 0.6), ("pop", 4, 0.9, 0.5, 0.7), ("pop", 4, 2.95, 0.5, 0.7),
    ("pop", 5, 0.3, 0.5, 0.7), ("tick", 5, 2.6, 0.6, 0.2), ("tick", 5, 5.2, 0.6, 0.2), ("tick", 5, 7.1, 0.6, 0.2),
    ("whoosh", 5, 8.7, 0.35, 0.6), ("pop", 5, 9.2, 0.5, 0.7), ("whoosh", 5, 10.6, 0.35, 0.6), ("pop", 5, 11.1, 0.5, 0.7),
    ("pop", 6, 1.3, 0.5, 0.7), ("pop", 6, 3.15, 0.5, 0.7), ("tick", 6, 3.9, 0.7, 0.2),
    ("whoosh", 7, 0.3, 0.4, 0.6), ("pop", 7, 1.3, 0.4, 0.7),
    ("pop", 9, 0.4, 0.5, 0.7), ("pop", 9, 2.3, 0.6, 0.7),
    ("whoosh", 10, 0.15, 0.5, 0.6), ("pop", 10, 0.9, 0.5, 0.7),
]
SFX += [("tick", 8, 1.75 + k * 0.125, 0.4, 0.12) for k in range(8)]
for n, (f, shot, t, vol, dur) in enumerate(SFX):
    clip(f"sfx{n:02d}", f"assets/sfx/{f}.mp3", S[shot - 1] + t, dur, vol, 4 + n % 3)

# ---- grid of 25 faces for shot 8
grid = []
for i in range(25):
    x, y = 1080 + 120 * (i % 5), 240 + 120 * (i // 5)
    grid.append(f'<use id="s8c{i}" class="s8c" href="#face-calm" x="{x}" y="{y}" width="96" height="96" />')
    if i in DROPPED:
        grid.append(f'<use id="s8d{i}" href="#face-dropped" x="{x}" y="{y}" width="96" height="96" opacity="0" />')

src = (HERE / "src/index.src.html").read_text(encoding="utf8")
src = src.replace("<!-- GENERATED from index.src.html by build.py; edit the source, then run: python build.py -->",
                  "<!-- GENERATED by build.py from index.src.html: edit the source, then run python build.py -->")
for i in range(10):
    src = src.replace(f"/*CLIP{i + 1}*/", f'data-start="{S[i]}" data-duration="{round(ends[i] - S[i], 3)}"')
src = (src.replace("/*TOTAL*/", str(TOTAL)).replace("/*S*/", json.dumps(S)).replace("/*CAPS*/", json.dumps(caps))
       .replace("/*DROPPED*/", json.dumps(DROPPED)).replace("<!--CAPTIONS-->", "\n".join(cap_html))
       .replace("<!--AUDIO-->", "\n".join(audio)).replace("<!--GRID-->", "\n          ".join(grid)))
assert not re.search(r"/\*[A-Z0-9]+\*/|<!--[A-Z]+-->", src), "unfilled marker"
(HERE / "index.html").write_text(src, encoding="utf8")
print(f"index.html: {len(caps)} caption chunks, {len(audio)} audio clips, {TOTAL}s")
